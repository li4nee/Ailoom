import { Check, Column, CreateDateColumn, Entity, ForeignKey, Index, PrimaryColumn } from 'typeorm';

import type { WorkspaceId } from '../../db/ids';
import { TenantEntity } from '../../db/tenant-entity';

/** Immutable generated snapshot metadata and content for agent-assist work. */
@Entity({ name: 'conversation_ai_artifacts' })
@Check('conversation_ai_artifacts_kind_check', `"kind" IN ('handoff_summary')`)
@Check(
  'conversation_ai_artifacts_state_check',
  `"state" IN ('queued', 'running', 'ready', 'failed')`,
)
@Index('conversation_ai_artifacts_latest', { synchronize: false })
@Index('conversation_ai_artifacts_one_active_summary', { synchronize: false })
export class ConversationAiArtifactEntity extends TenantEntity {
  @PrimaryColumn({ type: 'uuid', default: () => 'uuidv7()' })
  override id!: string;

  @ForeignKey('WorkspaceEntity', {
    name: 'conversation_ai_artifacts_workspace_fkey',
    onDelete: 'CASCADE',
  })
  @Column({ type: 'uuid' })
  override workspaceId!: WorkspaceId;

  @ForeignKey('BotEntity', { name: 'conversation_ai_artifacts_bot_fkey', onDelete: 'CASCADE' })
  @Column({ type: 'uuid' })
  botId!: string;

  @ForeignKey('ConversationEntity', {
    name: 'conversation_ai_artifacts_conversation_fkey',
    onDelete: 'CASCADE',
  })
  @Column({ type: 'uuid' })
  conversationId!: string;

  @Column({ type: 'text' })
  kind!: 'handoff_summary';

  @Column({ type: 'text' })
  state!: 'queued' | 'running' | 'ready' | 'failed';

  @Column({ type: 'uuid', nullable: true })
  sourceThroughMessageId!: string | null;

  @Column({ type: 'text' })
  promptVersion!: string;

  @Column({ type: 'uuid', nullable: true })
  traceId!: string | null;

  /** Null means generated by the automatic handoff listener. */
  @ForeignKey('UserEntity', {
    name: 'conversation_ai_artifacts_creator_fkey',
    onDelete: 'SET NULL',
  })
  @Column({ type: 'uuid', nullable: true })
  createdByUserId!: string | null;

  @Column({ type: 'jsonb', nullable: true })
  content!: Record<string, unknown> | null;

  @Column({ type: 'text', nullable: true })
  error!: string | null;

  @CreateDateColumn({ type: 'timestamptz' })
  createdAt!: Date;
}
