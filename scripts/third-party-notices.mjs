#!/usr/bin/env node
// SPDX-License-Identifier: AGPL-3.0-only
/**
 * Regenerate THIRD_PARTY_NOTICES.md from the production dependency tree.
 *
 *   node scripts/third-party-notices.mjs
 *
 * The static sections cover material that is bundled but is not an npm dependency.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const raw = execFileSync('pnpm', ['-r', 'licenses', 'list', '--prod', '--json'], {
  cwd: root,
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});
const byLicense = JSON.parse(raw);

const lines = [
  '<!-- SPDX-License-Identifier: AGPL-3.0-only -->',
  '',
  '# Third-party notices',
  '',
  'Generated by `node scripts/third-party-notices.mjs`. Do not edit the npm dependency',
  'section by hand.',
  '',
  '## Production npm dependencies',
  '',
];

for (const license of Object.keys(byLicense).sort()) {
  lines.push(`### ${license}`, '');
  const packages = [...byLicense[license]].sort((a, b) => a.name.localeCompare(b.name));
  for (const pkg of packages) {
    const versions = [...new Set(pkg.versions)].sort().join(', ');
    lines.push(`- \`${pkg.name}\` ${versions}`);
  }
  lines.push('');
}

lines.push(
  '## Bundled non-npm material',
  '',
  '### `apps/api/src/modules/auth/domain/common-passwords.txt`',
  '',
  '- Source: SecLists, `Passwords/Common-Credentials/Pwdb_top-10000.txt`,',
  '  <https://github.com/danielmiessler/SecLists>.',
  '- License: MIT © Daniel Miessler. Full text: `LICENSES/MIT.txt`.',
  '- Used for: rejecting common passwords during signup and password changes.',
  '',
  '### Local embedding model (`bge-small-en-v1.5`)',
  '',
  '- Source: BAAI `bge-small-en-v1.5`, converted to ONNX by Xenova and downloaded',
  '  from <https://huggingface.co/Xenova/bge-small-en-v1.5>.',
  '- License: MIT. Full text: `LICENSES/MIT.txt`.',
  '- Used for: offline embeddings when `LOCAL_EMBEDDINGS=true`. The model is',
  '  downloaded at runtime into the model volume, not baked into the image.',
  '',
  '### `apps/admin/public/sounds/needs-human.mp3`',
  '',
  '- Source: generated for this project with FFmpeg from a 660 Hz sine tone.',
  '- License: CC0 1.0 (public domain dedication).',
  '- Used for: the optional desktop notification when a conversation needs a person.',
  '',
);

writeFileSync(new URL('../THIRD_PARTY_NOTICES.md', import.meta.url), `${lines.join('\n')}`);
